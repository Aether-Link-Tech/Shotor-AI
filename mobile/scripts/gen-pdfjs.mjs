// Packs pdf.js into a JS module so PDFs can be read fully offline inside a hidden WebView.
// Run after upgrading pdfjs-dist:  npm run gen:pdfjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const build = join(root, 'node_modules', 'pdfjs-dist', 'build');
const main = readFileSync(join(build, 'pdf.min.mjs'), 'utf8');
const worker = readFileSync(join(build, 'pdf.worker.min.mjs'), 'utf8');
const version = JSON.parse(readFileSync(join(root, 'node_modules', 'pdfjs-dist', 'package.json'), 'utf8')).version;

for (const [name, src] of [['main', main], ['worker', worker]]) {
  if (src.includes('</script')) throw new Error(`pdf.js ${name} contains "</script" and cannot be inlined`);
}

const out = join(root, 'src', 'lib', 'docs', 'pdfjs.generated.js');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(
  out,
  `/* eslint-disable */\n// GENERATED by scripts/gen-pdfjs.mjs from pdfjs-dist ${version} (Apache-2.0). Do not edit.\n` +
    `export const PDFJS_VERSION = ${JSON.stringify(version)};\n` +
    `export const PDFJS_MAIN = ${JSON.stringify(main)};\n` +
    `export const PDFJS_WORKER = ${JSON.stringify(worker)};\n`,
);
console.log(`wrote ${out} (pdf.js ${version}, ${((main.length + worker.length) / 1e6).toFixed(2)} MB)`);
